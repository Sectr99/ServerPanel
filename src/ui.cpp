// Background: the screen's accent faintly at the top, fading into the base colour by 60% of the height. bgAt gives
// the colour behind any row, for rounding corners over it.
static bool sizeSprite(LGFX_Sprite& s, int w, int h);

// A full-screen vertical gradient from c0 at the top to c1 at `span` of the height, dithered, and kept in `cache`
// until its colours change: dithering every pixel takes a moment, copying the cache doesn't.
struct Gradient { LGFX_Sprite sprite; uint32_t c0 = 1, c1 = 1; float span = 0; };
static void gradient(Gradient& g, uint32_t c0, uint32_t c1, float span) {
  auto at = [&](int y) { return mix(c1, c0, clampf(y / (H * span), 0, 1)); };
  if (g.c0 != c0 || g.c1 != c1 || g.span != span || g.sprite.width() != W) {
    if (!sizeSprite(g.sprite, W, H)) {  // no room for the cache: plain rows
      for (int y = 0; y < H; y++) spr.drawFastHLine(0, y, W, at(y));
      return;
    }
    for (int y = 0; y < H; y++) {
      const uint32_t c = at(y);
      for (int x = 0; x < W; x++) g.sprite.drawPixel(x, y, dither(c, x, y));
    }
    g.c0 = c0; g.c1 = c1; g.span = span;
  }
  g.sprite.pushSprite(&spr, 0, 0);
}

static uint32_t bgTop = 0;
static uint32_t bgAt(int y) { return mix(C_BG, bgTop, clampf(y / (H * 0.6f), 0, 1)); }
static void background(uint32_t accent, float strength = 0.10f) {
  static Gradient g;
  bgTop = mix(accent, C_BG, strength);
  gradient(g, bgTop, C_BG, 0.6f);
}

