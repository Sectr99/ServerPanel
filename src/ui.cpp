// ---------- weather radar: NOAA radar over an Esri dark gray map (radar.cpp downloads; the image work is here) ----------
void uiRadarOrigin(float lat, float lon, int z, double& left, double& top) {
  const double world = 256.0 * (1 << z), s = sin(lat * M_PI / 180);
  const double cx = (lon + 180) / 360 * world, cy = (0.5 - log((1 + s) / (1 - s)) / (4 * M_PI)) * world;
  left = floor(cx - RADAR_W / 2.0);  // whole pixels, so the tiles and the radar image line up exactly
  top = floor(cy - RADAR_H / 2.0);
}

void uiRadarBBox(float lat, float lon, int z, double& minX, double& minY, double& maxX, double& maxY) {
  const double o = M_PI * 6378137.0, res = 2 * o / (256.0 * (1 << z));  // EPSG:3857 metres per pixel at zoom z
  double left, top;
  uiRadarOrigin(lat, lon, z, left, top);
  minX = left * res - o;  maxX = (left + RADAR_W) * res - o;
  maxY = o - top * res;   minY = o - (top + RADAR_H) * res;
}

// Draws every 256 px tile the map covers into dst, over what's there. JPEG or PNG, by the first bytes.
static bool radarTiles(LGFX_Sprite& dst, float lat, float lon, int z, RadarTileFn tile) {
  double left, top;
  uiRadarOrigin(lat, lon, z, left, top);
  const int n = 1 << z;
  bool all = true;
  for (int ty = int(floor(top / 256)); ty * 256.0 < top + RADAR_H; ty++)
    for (int tx = int(floor(left / 256)); tx * 256.0 < left + RADAR_W; tx++) {
      if (ty < 0 || ty >= n) continue;  // beyond the poles: nothing to fetch
      const uint8_t* img;
      size_t len;
      if (!tile(z, (tx % n + n) % n, ty, img, len) || len < 4) { all = false; continue; }
      const int x = int(tx * 256 - left), y = int(ty * 256 - top);
      all &= img[0] == 0xFF && img[1] == 0xD8 ? dst.drawJpg(img, len, x, y) : dst.drawPng(img, len, x, y);
    }
  return all;
}

bool uiRadarLayer(LGFX_Sprite& dst, float lat, float lon, int z, RadarTileFn tile, uint32_t fill) {
  if (!sizeSprite(dst, RADAR_W, RADAR_H)) return false;
  dst.fillScreen(fill);
  return radarTiles(dst, lat, lon, z, tile);
}

bool uiRadarCompose(LGFX_Sprite& dst, const LGFX_Sprite& base, const uint8_t* png, size_t len, const LGFX_Sprite* labels) {
  if (!sizeSprite(dst, base.width(), base.height())) return false;
  memcpy(dst.getBuffer(), const_cast<LGFX_Sprite&>(base).getBuffer(), size_t(base.width()) * base.height() * 2);
  bool ok = dst.drawPng(png, len, 0, 0);
  // Labels' anti-aliased edges were blended toward black, so they keep a thin dark halo over the radar.
  if (labels) const_cast<LGFX_Sprite*>(labels)->pushSprite(&dst, 0, 0, RADAR_CLEAR);
  return ok;
}

