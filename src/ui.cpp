// ---------- palette (uint32_t = RGB888 in LovyanGFX) ----------
// The palette as it shows by day; night mode scales it by THEME_NIGHT / THEME_DAY (config.h), so the whole theme
// dims in software even if the backlight can't.
constexpr uint32_t BASE[] = {
    0x0F1419, 0x1A2129, 0x2A333D, 0x232B35,  // bg, card, track, grid: slate blue-gray
    0xE6EAF0, 0x9AA6B6, 0x66717F,            // text, muted, dim
    0x2FB1FF, 0x9A7BE6, 0x2394D6, 0x34D29A,  // cyan (series 1), violet, blue, green
    0xFFD050, 0xFF6A4A,                      // amber, red: status only, kept apart from the series colors
    0x2EDBA3, 0xFF7BAD, 0xE8A6FF};           // teal, pink (series 2), orchid: gradient tops
// Series 1/2 (cyan/pink), gradient tops and amber/red pass the dataviz palette checks (CVD, contrast) at THEME_DAY.
static uint32_t C_BG, C_CARD, C_TRACK, C_GRID, C_TEXT, C_MUTED, C_DIM, C_CYAN, C_VIOLET, C_BLUE, C_GREEN, C_AMBER, C_RED,
    C_TEAL, C_PINK, C_ORCHID;

static float palK = 1;  // the current palette scale: THEME_DAY or THEME_NIGHT
static void setPalette(float k) {
  palK = k;
  uint32_t* slots[] = {&C_BG, &C_CARD, &C_TRACK, &C_GRID, &C_TEXT, &C_MUTED, &C_DIM,
                       &C_CYAN, &C_VIOLET, &C_BLUE, &C_GREEN, &C_AMBER, &C_RED, &C_TEAL, &C_PINK, &C_ORCHID};
  for (int i = 0; i < 16; i++) {
    uint32_t c = BASE[i];
    auto ch = [&](int s) { return uint32_t(((c >> s) & 255) * k) << s; };
    *slots[i] = ch(16) | ch(8) | ch(0);
  }
}

