// "9:47" + "PM" in 12-hour mode (returns the suffix), "21:47" + nullptr in 24-hour mode.
static const char* fmtClock(char* buf, size_t n, const tm* t) {
  if (settings.clock24) { snprintf(buf, n, "%02d:%02d", t->tm_hour, t->tm_min); return nullptr; }
  snprintf(buf, n, "%d:%02d", (t->tm_hour + 11) % 12 + 1, t->tm_min);  // no leading zero
  return t->tm_hour < 12 ? "AM" : "PM";
}

