// ---------- fonts for what Inter lacks: Japanese, accents (tools/mkfonts.py sd, on the microSD card) ----------
// Each text role draws from its Inter font and falls back to its card font for anything else, on the Inter font's
// baseline. The card fonts' glyphs are read from their files as they're drawn, so they take next to no RAM.

// A font file read through stdio: the card is mounted at /sdcard on the panel; the preview reads a folder. A read that
// comes up short means the card has gone (pulled out, or failing): from then on every role draws from Inter alone
// (missing glyphs show as boxes) rather than waiting on the card for each glyph.
struct StdioFile : lgfx::DataWrapper {
  static inline bool failed = false;  // one flag for all: the files share the card
  FILE* fp = nullptr;
  bool open(const char* path) override { return (fp = fopen(path, "rb")) != nullptr; }
  int read(uint8_t* buf, uint32_t len) override {
    const size_t n = failed ? 0 : fread(buf, 1, len, fp);
    if (n < len) failed = true;
    return int(n);
  }
  void skip(int32_t offset) override { fseek(fp, offset, SEEK_CUR); }
  bool seek(uint32_t offset) override {
    if (!failed && fseek(fp, long(offset), SEEK_SET)) failed = true;
    return !failed;
  }
  void close() override { if (fp) fclose(fp); fp = nullptr; }
  int32_t tell() override { return int32_t(ftell(fp)); }
};

struct FallbackFont : lgfx::IFont {
  const lgfx::VLWfont *a = nullptr, *b = nullptr;
  const lgfx::VLWfont* pick(uint16_t c) const {
    uint16_t i;
    return c > 0x7E && !StdioFile::failed && !a->getUnicodeIndex(c, &i) && b->getUnicodeIndex(c, &i) ? b : a;
  }
  font_type_t getType() const override { return ft_vlw; }
  void getDefaultMetric(lgfx::FontMetrics* m) const override { a->getDefaultMetric(m); }
  bool updateFontMetric(lgfx::FontMetrics* m, uint16_t c) const override { return pick(c)->updateFontMetric(m, c); }
  size_t drawChar(lgfx::LGFXBase* g, int32_t x, int32_t y, uint16_t c, const lgfx::TextStyle* st, lgfx::FontMetrics* m,
                  int32_t& filled) const override {
    const lgfx::VLWfont* f = pick(c);
    if (f != a) y += int32_t((a->maxAscent - f->maxAscent) * st->size_y);  // onto the first font's baseline
    return f->drawChar(g, x, y, c, st, m, filled);
  }
};

int uiLoadExtraFonts(const char* dir) {
  ensureFonts();
  const struct { const char* name; const lgfx::IFont** role; } r[7] = {
      {"small", &F_SMALL}, {"body", &F_BODY}, {"bodyb", &F_BODYB}, {"stat", &F_STAT}, {"title", &F_TITLE},
      {"big", &F_BIG}, {"huge", &F_HUGE}};
  static StdioFile files[7];
  static lgfx::VLWfont extra[7];
  static FallbackFont wrap[7];
  int n = 0;
  for (int i = 0; i < 7; i++) {
    if ((*r[i].role)->getType() != lgfx::IFont::ft_vlw || wrap[i].b) continue;  // bitmap fonts, or already loaded
    char path[128];
    snprintf(path, sizeof path, "%s/%s.vlw", dir, r[i].name);
    if (!files[i].open(path)) continue;
    if (!extra[i].loadFont(&files[i])) {  // a damaged file: skip it, without giving up on the rest
      files[i].close();
      StdioFile::failed = false;
      continue;
    }
    wrap[i].a = static_cast<const lgfx::VLWfont*>(*r[i].role);
    wrap[i].b = &extra[i];
    *r[i].role = &wrap[i];
    n++;
  }
  return n;
}

// ---------- history ----------
// Each graph point is the mean of every reading taken during its slot, not one instant reading.
struct Hist {
  float v[HIST_N]; int head = 0, count = 0;
  double sum = 0; int n = 0;
  void add(float x) { if (!isnan(x)) { sum += x; n++; } }
  void commit() { push(n ? float(sum / n) : NAN); sum = 0; n = 0; }
  void push(float x) { v[head] = x; head = (head + 1) % HIST_N; if (count < HIST_N) count++; }
  float at(int i) const { return v[(head - count + i + HIST_N) % HIST_N]; }  // 0 = oldest
  float max() const { float m = 0; for (int i = 0; i < count; i++) if (at(i) > m) m = at(i); return m; }
};
static Hist hPcCpu, hPcGpu, hPcCpuT, hPcGpuT, hPcRam, hNasCpu, hNasCpuT, hNasGpu, hNasGpuT, hNasRam, hRx, hTx, hPrNoz, hPrBed;
#define ALL_HIST &hPcCpu, &hPcGpu, &hPcCpuT, &hPcGpuT, &hPcRam, &hNasCpu, &hNasCpuT, &hNasGpu, &hNasGpuT, &hNasRam, &hRx, &hTx, \
                 &hPrNoz, &hPrBed

// Per-disk (a = temp, b = used %) and per-container (a = CPU %, b = memory MB) history, keyed by name
// because those lists can reorder or change between polls.
struct Named { char name[28]; Hist a, b; };
static Named diskH[MAX_DISKS], ctrH[MAX_CTR];
static Named* named(Named* pool, int n, const char* name, bool create) {
  for (int i = 0; i < n; i++) if (!strcmp(pool[i].name, name)) return &pool[i];
  if (create)
    for (int i = 0; i < n; i++)
      if (!pool[i].name[0]) { snprintf(pool[i].name, sizeof pool[i].name, "%s", name); return &pool[i]; }
  return nullptr;
}

void uiSample(const Data& d, const Status& s, bool commit) {
  hPcCpu.add(s.pc ? d.pcCpu : NAN);    hPcGpu.add(s.pc ? d.pcGpu : NAN);
  hPcCpuT.add(s.pc ? d.pcCpuT : NAN);  hPcGpuT.add(s.pc ? d.pcGpuT : NAN);
  hPcRam.add(s.pc ? d.pcRam : NAN);
  hNasCpu.add(s.nas ? d.nasCpu : NAN); hNasCpuT.add(s.nas ? d.nasCpuT : NAN); hNasRam.add(s.nas ? d.nasRam : NAN);
  hNasGpu.add(s.nas ? d.nasGpu : NAN); hNasGpuT.add(s.nas ? d.nasGpuT : NAN);
  hRx.add(s.nas ? d.nasRx : NAN);      hTx.add(s.nas ? d.nasTx : NAN);
  hPrNoz.add(s.printer ? d.pr.noz : NAN); hPrBed.add(s.printer ? d.pr.bed : NAN);
  for (int i = 0; s.unraid && i < d.nDisks; i++)
    if (Named* h = named(diskH, MAX_DISKS, d.disks[i].name, true)) {
      h->a.add(d.disks[i].temp > 0 ? d.disks[i].temp : NAN);  // asleep = gap
      h->b.add(d.disks[i].pct);
    }
  for (int i = 0; s.docker && i < d.nCtr; i++)
    if (Named* h = named(ctrH, MAX_CTR, d.ctr[i].name, true)) {
      bool up = strcmp(d.ctr[i].status, "exited") && strcmp(d.ctr[i].status, "created");
      h->a.add(up ? d.ctr[i].cpu : NAN);
      h->b.add(up ? d.ctr[i].memMB : NAN);
    }
  if (!commit) return;
  for (Hist* h : {ALL_HIST}) h->commit();
  for (int i = 0; i < MAX_DISKS; i++) if (diskH[i].name[0]) { diskH[i].a.commit(); diskH[i].b.commit(); }
  for (int i = 0; i < MAX_CTR; i++) if (ctrH[i].name[0]) { ctrH[i].a.commit(); ctrH[i].b.commit(); }
}

// Graph window change: old points were spaced differently, so start the graphs over.
static void clearHistory() {
  for (Hist* h : {ALL_HIST}) *h = Hist();
  for (Named& n : diskH) { n.a = Hist(); n.b = Hist(); }
  for (Named& n : ctrH) { n.a = Hist(); n.b = Hist(); }
}

// ---------- navigation state + tap targets ----------
// Every tappable thing registers its rectangle while it is drawn; uiTap() matches against the last frame.
enum Act : uint8_t { ACT_PAGE, ACT_GAUGE, ACT_DISK, ACT_CTR, ACT_SETTINGS, ACT_SET, ACT_APP, ACT_MACRO, ACT_DECK, ACT_CAM,
                    ACT_RADAR,    // an op on the radar screen or its location sheet (RadarOp)
                    ACT_SPOTIFY };  // a Spotify control (SpotifyCmd); seek and volume read the tap's x
enum GaugeId : uint8_t { G_PC_CPU, G_PC_CPUT, G_PC_GPU, G_PC_GPUT, G_PC_RAM, G_NAS_CPU, G_NAS_CPUT, G_NAS_RAM, G_NAS_GPU, G_NAS_GPUT,
                        G_PR_NOZ, G_PR_BED,
                        G_ARRAY };  // also indexes the detail table in drawDetail; ARRAY opens the storage page instead
struct Hit { int16_t x, y, w, h; Act act; uint8_t arg; char name[28]; };
static Hit hits[48];
static int nHits = 0;
static void hit(int x, int y, int w, int h, Act act, uint8_t arg, const char* name = "") {
  if (nHits == 48) return;
  Hit& t = hits[nHits++];
  t.x = x; t.y = y; t.w = w; t.h = h; t.act = act; t.arg = arg;
  snprintf(t.name, sizeof t.name, "%s", name);
}

enum Detail : uint8_t { DET_NONE, DET_GAUGE, DET_DISK, DET_CTR, DET_SETTINGS, DET_CAMERA };
static Page page = PAGE_PC;
static Detail detail = DET_NONE;
static bool home = false;  // launcher showing; the apps keep their state underneath
static uint8_t app = FN_STATS;  // an app's Function: any but FN_LAUNCHER
static bool dropOpen = false;   // settings: Function dropdown list showing
static bool radarSheet = false; // weather radar: the location sheet is open
static bool spVolume = false;   // spotify: the control strip shows the volume slider instead of the buttons
static uint8_t spSheet = 0;     // spotify: 0 the player, or the library or devices sheet (SPU_LIBRARY, SPU_DEVICES)
static int8_t radarAlert = -1;  // weather radar: the alert sheet shows this alert; -1 = closed
static int8_t macroTapped = -1, macroFlash = -1;  // flash: key drawn highlighted for one frame
const Macro MACROS[] = MACRO_KEYS;
const int N_MACROS = sizeof MACROS / sizeof MACROS[0];
static uint8_t detailGauge = 0;
static char detailName[28] = "";

void uiShowPage(Page p) {  // PAGE_COUNT = launcher
  home = p >= PAGE_COUNT;
  if (!home) { page = p; app = FN_STATS; }
  detail = DET_NONE;
}
void uiShowLauncher() { home = true; detail = DET_NONE; }
static void openFunction() {  // switch to the Function's app (or the launcher), leaving any detail view as is
  home = settings.function == FN_LAUNCHER;
  if (!home) app = settings.function;
}
void uiHome() { detail = DET_NONE; page = Page(settings.startPage); openFunction(); }
int uiTakeMacro() { int m = macroTapped; macroTapped = -1; return m; }
static int8_t deckTapped = -1, deckFlash = -1;
int uiTakeDeckPress() { int k = deckTapped; deckTapped = -1; return k; }
void uiNextPage() { if (detail == DET_NONE && !home && app == FN_STATS) page = Page((page + 1) % PAGE_COUNT); }

void uiSwipe(int dir) {  // +1 = next page, -1 = previous; in a detail view any swipe just closes it
  if (detail != DET_NONE) { detail = DET_NONE; return; }
  if (!home && app == FN_SPOTIFY && spSheet) { spSheet = 0; return; }  // a swipe closes the library or devices sheet
  if (!home && app == FN_RADAR && (radarSheet || radarAlert >= 0)) {  // a swipe closes the location or alert sheet
    radarSheet = false;
    radarAlert = -1;
    return;
  }
  if (home || app != FN_STATS) return;  // only server stats has pages
  page = Page((page + PAGE_COUNT + dir) % PAGE_COUNT);
}

static void applyOp(uint8_t op);
static bool isDropOption(uint8_t op);  // an entry in the open Function list
static void radarOp(uint8_t op);       // a tap on the radar screen or its location sheet
static void spotifyOp(uint8_t cmd, float at);  // a Spotify control; at = where across it the tap landed, 0-1

void uiTap(int x, int y) {
  if (detail == DET_SETTINGS) {  // settings only react to their controls; with the dropdown open, only to its list
    for (int i = nHits - 1; i >= 0; i--) {
      const Hit& t = hits[i];
      if (t.act != ACT_SET || x < t.x || y < t.y || x >= t.x + t.w || y >= t.y + t.h) continue;
      if (!dropOpen || isDropOption(t.arg)) applyOp(t.arg);
      else dropOpen = false;
      return;
    }
    dropOpen = false;
    return;
  }
  if (detail != DET_NONE) { detail = DET_NONE; return; }  // any tap closes a detail view
  for (int i = nHits - 1; i >= 0; i--) {
    const Hit& t = hits[i];
    if (x < t.x || y < t.y || x >= t.x + t.w || y >= t.y + t.h) continue;
    switch (t.act) {
      case ACT_PAGE: page = Page(t.arg); return;
      case ACT_GAUGE:
        if (t.arg == G_ARRAY) { page = PAGE_STORAGE; return; }  // the array has its own page
        detail = DET_GAUGE; detailGauge = t.arg; return;
      case ACT_DISK: detail = DET_DISK; snprintf(detailName, sizeof detailName, "%s", t.name); return;
      case ACT_CTR: detail = DET_CTR; snprintf(detailName, sizeof detailName, "%s", t.name); return;
      case ACT_SETTINGS: detail = DET_SETTINGS; dropOpen = false; return;
      case ACT_SET: return;
      case ACT_APP:  // an app opens on its main screen, not on a sheet left open last time
        home = false;
        app = t.arg;
        radarSheet = false;
        radarAlert = -1;
        spSheet = 0;
        spVolume = false;
        return;
      case ACT_MACRO: macroTapped = macroFlash = t.arg; return;
      case ACT_DECK: deckTapped = deckFlash = t.arg; return;
      case ACT_CAM: detail = DET_CAMERA; return;
      case ACT_RADAR: radarOp(t.arg); return;
      case ACT_SPOTIFY: spotifyOp(t.arg, clampf((x - t.x - 12) / float(t.w - 24), 0, 1)); return;  // 12: the hit's padding
    }
  }
  // A tap on nothing does nothing: pages change by swiping.
}

bool uiDrag(int x0, int y0, int x1) {
  if (detail != DET_NONE) return false;
  for (int i = nHits - 1; i >= 0; i--) {
    const Hit& t = hits[i];
    if (t.act != ACT_SPOTIFY || (t.arg != SP_SEEK && t.arg != SP_VOLUME)) continue;
    if (x0 < t.x || y0 < t.y || x0 >= t.x + t.w || y0 >= t.y + t.h) continue;
    spotifyOp(t.arg, clampf((x1 - t.x - 12) / float(t.w - 24), 0, 1));  // 12: the hit's padding, as in uiTap
    return true;
  }
  return false;
}

// ---------- drawing helpers ----------
static uint32_t mix(uint32_t a, uint32_t b, float t) {  // t=1 -> a
  auto ch = [&](int s) { return uint32_t(((a >> s) & 255) * t + ((b >> s) & 255) * (1 - t)) << s; };
  return ch(16) | ch(8) | ch(0);
}
static uint32_t sev(float v, float warn, float crit, uint32_t base) {
  return v >= crit ? C_RED : v >= warn ? C_AMBER : base;
}
static void text(int x, int y, const char* s, const lgfx::IFont* f, uint32_t col, textdatum_t d = top_left) {
  spr.setFont(f);
  spr.setTextColor(col);
  spr.setTextDatum(d);
  spr.drawString(s, x, y);
}
static void dot(int x, int y, uint32_t col) { spr.fillSmoothCircle(x, y, 4, col); }

// Draws s, cut short with "..." to fit w pixels.
static void textFit(int x, int y, const char* s, int w, const lgfx::IFont* f, uint32_t col,
                    textdatum_t d = top_left) {
  char buf[160];
  snprintf(buf, sizeof buf, "%s", s);
  spr.setFont(f);
  if (spr.textWidth(buf) > w)  // drop whole characters (UTF-8: a lead byte and its continuation bytes) until it fits
    for (size_t n = strlen(buf); n > 0;) {
      do n--; while (n > 0 && (buf[n] & 0xC0) == 0x80);
      strcpy(buf + n, "...");
      if (spr.textWidth(buf) <= w) break;
    }
  text(x, y, buf, f, col, d);
}

// Sample i of `count` (0 = oldest) spans [xa, xb) when HIST_N samples are stretched across w pixels.
struct XScale {
  int x, w, count; float px;
  XScale(int x, int w, int count) : x(x), w(w), count(count), px(w / float(HIST_N)) {}
  int xa(int i) const { return x + w - int(lroundf((count - i) * px)); }
  int xb(int i) const { return x + w - int(lroundf((count - i - 1) * px)); }
  float xc(int i) const { return x + w - (count - i - 0.5f) * px; }
};

// Y range that fits the window's data with 10% headroom, at least a fifth of [lo, hi] tall (so idle jitter isn't
// blown up into big waves), rounded out to multiples of 5 so it only moves when the data really does.
static std::pair<float, float> fitRange(const Hist& a, float lo, float hi) {
  float mn = NAN, mx = NAN;
  for (int i = 0; i < a.count; i++)
    if (!isnan(a.at(i))) { mn = isnan(mn) ? a.at(i) : fminf(mn, a.at(i)); mx = isnan(mx) ? a.at(i) : fmaxf(mx, a.at(i)); }
  if (isnan(mn)) return {lo, hi};
  float pad = fmaxf((mx - mn) * 0.1f, 1), b0 = mn - pad, b1 = mx + pad, span = (hi - lo) / 5;
  if (b1 - b0 < span) { float c = (b0 + b1) / 2; b0 = c - span / 2; b1 = c + span / 2; }
  b0 = floorf(b0 / 5) * 5; b1 = ceilf(b1 / 5) * 5;
  if (b0 < lo) { b1 += lo - b0; b0 = lo; }
  if (b1 > hi) { b0 = fmaxf(lo, b0 - (b1 - hi)); b1 = hi; }
  return {b0, b1};
}

// A colour (RGB888) nudged by a 4 x 4 Bayer pattern below the bits RGB565 drops, for gradients: a plain fade shows
// visible bands on the panel.
static uint32_t dither(uint32_t c, int x, int y) {
  static const uint8_t bayer[16] = {0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5};
  const float d = (bayer[(y & 3) * 4 + (x & 3)] + 0.5f) / 16;
  auto ch = [&](int sh, int step) { return uint32_t(std::min(255, int((c >> sh) & 255) + int(d * step))); };
  return ch(16, 8) << 16 | ch(8, 4) << 8 | ch(0, 8);
}

// An area chart of one history, newest at the right: a smoothed 2.5 px line over a fill that fades toward the
// bottom, and a dot on the latest point. zoom: the y axis fits the data (fitRange within [lo, hi]); otherwise [lo, hi]
// as given. sqrtY: a square-root axis, so normal traffic stays visible after a big burst. Gaps stay gaps. under: the
// colour behind it. Returns the y range used.
static std::pair<float, float> chart(int x, int y, int w, int h, const Hist& a, uint32_t col, float lo, float hi,
                                     bool zoom = true, bool sqrtY = false, uint32_t under = 0) {
  if (!under) under = C_CARD;
  auto [vlo, vhi] = zoom ? fitRange(a, lo, hi) : std::pair{lo, hi};
  static float sm[HIST_N];  // display-only smoothing: centred 9-point mean; the stored history is untouched
  for (int i = 0; i < a.count; i++) {
    float sum = 0; int n = 0;
    if (!isnan(a.at(i)))
      for (int j = std::max(0, i - 4); j <= std::min(a.count - 1, i + 4); j++)
        if (!isnan(a.at(j))) { sum += a.at(j); n++; }
    sm[i] = n ? sum / n : NAN;
  }
  auto py = [&](float v) {
    float f = clampf((v - vlo) / (vhi - vlo), 0, 1);
    return y + h - 3 - (sqrtY ? sqrtf(f) : f) * (h - 6);
  };
  const uint32_t top = mix(col, under, 0.30f), bot = mix(col, under, 0.02f);
  XScale sx(x, w, a.count);
  for (int i = 0; i < a.count; i++) {
    if (isnan(sm[i])) continue;
    int yv = py(sm[i]);
    for (int gx = sx.xa(i); gx < sx.xb(i); gx++)
      for (int yy = yv; yy < y + h; yy++) spr.drawPixel(gx, yy, dither(mix(top, bot, 1 - float(yy - y) / h), gx, yy));
  }
  for (int i = 1; i < a.count; i++)
    if (!isnan(sm[i - 1]) && !isnan(sm[i])) spr.drawWideLine(sx.xc(i - 1), py(sm[i - 1]), sx.xc(i), py(sm[i]), 1.25f, col);
  if (a.count && !isnan(sm[a.count - 1])) {
    int ey = py(sm[a.count - 1]);
    spr.fillSmoothCircle(x + w - 5, ey, 7, under);
    spr.fillSmoothCircle(x + w - 5, ey, 5, col);
  }
  return {vlo, vhi};
}

static void fmtRate(char* buf, size_t n, float bps) {
  if (isnan(bps)) snprintf(buf, n, "--");
  else if (bps >= 1e9f) snprintf(buf, n, "%.2f Gb/s", bps / 1e9f);
  else if (bps >= 1e8f) snprintf(buf, n, "%.0f Mb/s", bps / 1e6f);  // 682 Mb/s, not 682.0
  else if (bps >= 1e6f) snprintf(buf, n, "%.1f Mb/s", bps / 1e6f);
  else snprintf(buf, n, "%.0f kb/s", bps / 1e3f);
}

static void fmtMem(char* buf, size_t n, float mb) {
  if (mb >= 1024) snprintf(buf, n, "%.1f GB", mb / 1024);
  else snprintf(buf, n, "%.0f MB", mb);
}

