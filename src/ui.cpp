static float arrayPct(const Data& d, bool unraidOn) {
  return unraidOn && d.arraySizeKB > 0 ? 100 * (1 - d.arrayFreeKB / d.arraySizeKB) : NAN;
}

// Network rate as a hero value: "36" + "Mb/s".
static Val rateVal(float bps, const char* caption, uint32_t col) {
  Val r{{}, "", caption, col, 255};
  char buf[16];
  fmtRate(buf, sizeof buf, bps);
  char* sp = strchr(buf, ' ');
  if (sp) { *sp = 0; r.unit = bps >= 1e9f ? "Gb/s" : bps >= 1e6f ? "Mb/s" : "kb/s"; }
  snprintf(r.num, sizeof r.num, "%s", buf);
  return r;
}

