// Called by the Spotify task only (the scratch sprite is its own). Decodes at full size, then scales with
// anti-aliasing: drawJpg's own scaling is nearest-neighbour (the camera's screen-door grid). tint: the art's
// dominant colour. A 32 x 32 grid of samples goes into 12 hue bins, each weighted by its saturation; the heaviest
// bin's average wins. Averaging all of them mixed e.g. purple and orange into brown.
static LGFX_Sprite spFull;  // the Spotify task's scratch: a JPEG at full size
static bool squareDecode(LGFX_Sprite& dst, const uint8_t* jpg, size_t len, int size, int& jw, int& jh) {
  if (!jpegSize(jpg, len, jw, jh) || !sizeSprite(spFull, jw, jh) || !spFull.drawJpg(jpg, len, 0, 0) || !sizeSprite(dst, size, size))
    return false;
  float sc = std::max(float(size) / jw, float(size) / jh);
  dst.fillScreen(0);
  spFull.pushRotateZoomWithAA(&dst, size / 2.0f, size / 2.0f, 0, sc, sc);
  return true;
}
bool uiSpotifyCoverDecode(LGFX_Sprite& dst, const uint8_t* jpg, size_t len) {
  int jw, jh;
  return squareDecode(dst, jpg, len, SPOTIFY_COVER, jw, jh);
}

bool uiSpotifyDecode(LGFX_Sprite& dst, const uint8_t* jpg, size_t len, uint32_t& tint) {
  int jw, jh;
  if (!squareDecode(dst, jpg, len, SPOTIFY_ART, jw, jh)) return false;
  LGFX_Sprite& full = spFull;
  struct { float r, g, b, w; } bin[13] = {};  // 12 hues, then the greys
  for (int gy = 0; gy < 32; gy++)
    for (int gx = 0; gx < 32; gx++) {
      auto c = full.readPixelRGB(gx * jw / 32 + jw / 64, gy * jh / 32 + jh / 64);
      const int mx = std::max({c.r, c.g, c.b}), mn = std::min({c.r, c.g, c.b}), sat = mx - mn;
      int k = 12;
      if (sat > 24) {
        float h = mx == c.r ? float(c.g - c.b) / sat : mx == c.g ? 2 + float(c.b - c.r) / sat : 4 + float(c.r - c.g) / sat;
        k = int((h < 0 ? h + 6 : h) * 2) % 12;
      }
      const float w = 1 + sat;
      bin[k].r += c.r * w; bin[k].g += c.g * w; bin[k].b += c.b * w; bin[k].w += w;
    }
  int best = 12;
  for (int k = 0; k < 12; k++) if (bin[k].w > bin[best].w) best = k;
  const auto& m = bin[best];
  tint = m.w ? uint32_t(m.r / m.w) << 16 | uint32_t(m.g / m.w) << 8 | uint32_t(m.b / m.w) : 0x283240;
  return true;
}

