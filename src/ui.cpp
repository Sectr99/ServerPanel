// ---- camera ----
// The camera task decodes each JPEG at half size (uiCamDecode) and uiCamFrame copies the picture into camHalf. Each
// frame is then scaled once (per size) into a cached image, so the once-a-second redraws only copy pixels.
static LGFX_Sprite camHalf;  // the latest frame at half size (640x360)
static uint32_t camGen = 0;  // bumped per frame, so the cache knows to scale again

bool uiCamWanted() {
  return !home && app == FN_STATS && (detail == DET_CAMERA || (detail == DET_NONE && page == PAGE_PRINTER));
}

// A plain RGB565 sprite of w x h in PSRAM. Plain, not the panel's non-swapped format: the AA zoom mangles that one.
static bool sizeSprite(LGFX_Sprite& s, int w, int h) {
  if (s.width() == w && s.height() == h) return true;
  s.deleteSprite();
  s.setPsram(true);
  s.setColorDepth(16);
  return s.createSprite(w, h);
}

bool uiCamFrame(const LGFX_Sprite& half) {
  if (!sizeSprite(camHalf, half.width(), half.height())) return false;
  memcpy(camHalf.getBuffer(), const_cast<LGFX_Sprite&>(half).getBuffer(), size_t(half.width()) * half.height() * 2);
  camGen++;
  return uiCamWanted();
}

// Width and height from the JPEG's SOF0/SOF2 header.
static bool jpegSize(const uint8_t* d, size_t n, int& w, int& h) {
  for (size_t i = 2; i + 9 < n;) {
    if (d[i] != 0xFF) return false;
    uint8_t m = d[i + 1];
    if (m == 0xC0 || m == 0xC2) { h = d[i + 5] << 8 | d[i + 6]; w = d[i + 7] << 8 | d[i + 8]; return true; }
    i += 2 + (d[i + 2] << 8 | d[i + 3]);
  }
  return false;
}

// Decodes at exactly half size, which the JPEG decoder does natively (fast, no resampling); camImage then scales
// that with anti-aliasing. Letting drawJpg scale straight to the target size resamples nearest-neighbour, which
// drops or repeats whole rows and columns at regular intervals: a screen-door grid over the image.
bool uiCamDecode(LGFX_Sprite& dst, const uint8_t* jpg, size_t len) {
  int jw, jh;
  if (!jpegSize(jpg, len, jw, jh) || !sizeSprite(dst, jw / 2, jh / 2)) return false;
  return dst.drawJpg(jpg, len, 0, 0, jw / 2, jh / 2, 0, 0, 0.5f, 0.5f);
}

// Paints `under` over a rectangle's corners outside radius r, so a square image sits like a card.
// underBottom: another colour for the bottom corners (-1 = the same).
static void roundCorners(int x, int y, int w, int h, int r, uint32_t under, int64_t underBottom = -1) {
  for (int dy = 0; dy < r; dy++) {
    float fy = r - dy - 0.5f;
    int dx = r - int(sqrtf(r * r - fy * fy) + 0.5f);  // pixels outside the arc on this row
    if (dx <= 0) continue;
    for (int yy : {y + dy, y + h - 1 - dy}) {
      uint32_t c = yy > y + dy && underBottom >= 0 ? uint32_t(underBottom) : under;
      spr.drawFastHLine(x, yy, dx, c);
      spr.drawFastHLine(x + w - dx, yy, dx, c);
    }
  }
}

// The camera filling w x h (centre-cropped if the shape differs), with a red banner while the printer reports an
// error; a card with a message while there's no frame yet. full: the full-screen view (square corners, no chips,
// the banner at the top, clear of the progress line along the bottom).
static void camImage(const Printer& p, const Status& s, int x, int y, int w, int h, bool full = false) {
  static LGFX_Sprite cache;
  static uint32_t gen = 0;
  if (!camGen) {
    if (full) spr.fillRect(x, y, w, h, C_BG);
    else card(x, y, w, h);
    const char* msg = !*PRINTER_IP ? "Set PRINTER_IP in config.h"
                    : !s.printer   ? "Printer offline"
                                   : "Connecting to the camera...  (needs LAN Only Liveview on the printer)";
    text(x + w / 2, y + h / 2 - 34, ICON_VIDEOCAM_FILL, I_L, C_DIM, middle_center);
    text(x + w / 2, y + h / 2 + 30, msg, F_BODY, C_DIM, middle_center);
    return;
  }
  if (cache.width() != w || cache.height() != h) {
    if (!sizeSprite(cache, w, h)) { card(x, y, w, h); return; }
    gen = camGen - 1;  // new size: scale again
  }
  if (gen != camGen) {  // scale the half-size frame smoothly; pushSprite below converts to the panel's format
    float sc = std::max(float(w) / camHalf.width(), float(h) / camHalf.height());
    cache.fillScreen(C_BG);
    camHalf.pushRotateZoomWithAA(&cache, w / 2.0f, h / 2.0f, 0, sc, sc);  // centred, so any overflow crops evenly
    gen = camGen;
  }
  cache.pushSprite(&spr, x, y);
  if (!full) {
    roundCorners(x, y, w, h, 20, bgAt(y), bgAt(y + h));
    chip(x + w - 14, y + 28, s.cam ? "LIVE" : "Not live", s.cam ? C_GREEN : C_AMBER);  // a stale frame isn't taken as live
    spr.fillSmoothCircle(x + w - 34, y + h - 34, 20, C_BG);
    text(x + w - 34, y + h - 34, ICON_OPEN_IN_FULL, I_S, C_TEXT, middle_center);
  }
  if (s.printer && (p.err || !strcmp(p.state, "FAILED"))) {
    const int nStages = sizeof STAGES / sizeof *STAGES;
    char msg[80];
    int n = p.err ? snprintf(msg, sizeof msg, "Error %04X_%04X", unsigned(p.err >> 16), unsigned(p.err & 0xFFFF))
                  : snprintf(msg, sizeof msg, "Print failed");
    if (p.stage > 0 && p.stage < nStages) snprintf(msg + n, sizeof msg - n, "  /  %s", STAGES[p.stage]);
    const int bh = 48, bx = x + 14, by = full ? y + 70 : y + h - 14 - bh - 46, bw = w - 28 - (full ? 0 : 0);
    spr.fillSmoothRoundRect(bx, by, bw, bh, 16, C_RED);
    text(bx + 30, by + bh / 2, ICON_WARNING_FILL, I_S, C_BG, middle_center);
    textFit(bx + 52, by + bh / 2, msg, bw - 70, F_BODYB, C_BG, middle_left);  // dark on red: 6:1 contrast
  }
}

// What the printer is doing, for the progress card and the camera view: "42%", "1 h 23 min left", and a line with the
// layer and the clock time it should finish (not while paused: that time keeps slipping).
static void prProgress(const Printer& p, const tm* clock, char* left, size_t nl, char* line, size_t nline) {
  *left = *line = 0;
  if (p.mins >= 0) {
    char tag[24];
    fmtMins(tag, sizeof tag, p.mins);
    snprintf(left, nl, "%s left", tag);
  }
  if (p.layers) snprintf(line, nline, "layer %d / %d", p.layer, p.layers);
  if (strcmp(p.state, "PAUSE") && clock && p.mins > 0) {
    tm t = *clock;
    t.tm_min += p.mins;
    t.tm_sec = 0;
    t.tm_isdst = -1;  // let mktime work out DST for the finish time, in case the print runs across a change
    mktime(&t);
    char hm[16];
    const char* ampm = fmtClock(hm, sizeof hm, &t);
    size_t n = strlen(line);
    snprintf(line + n, nline - n, "%sdone %s%s%s", n ? "  /  " : "", hm, ampm ? " " : "", ampm ? ampm : "");
  }
}

