// ---------- settings: runtime-adjustable, saved to flash by main.cpp ----------
Settings settings = {1, BL_DAY, SLEEP_MINUTES, NIGHT_ON, NIGHT_FROM, NIGHT_TO, BL_NIGHT, PAGE_SECONDS, CLOCK_24H,
                      GRAPH_MINUTES, START_PAGE, PANEL_FUNCTION, RADAR_ZIP, RADAR_PLACE, RADAR_LAT, RADAR_LON, 0};

enum Op : uint8_t {
  OP_BACK, OP_BRIGHT_DN, OP_BRIGHT_UP, OP_NBRIGHT_DN, OP_NBRIGHT_UP, OP_NFROM_DN, OP_NFROM_UP, OP_NTO_DN, OP_NTO_UP,
  OP_NIGHT, OP_RESTART, OP_FUNC_OPEN,
  OP_SLEEP = 32,  // + option index
  OP_ROT = 40,    // + option index
  OP_CLOCK = 48,  // + 0 (12 h) / 1 (24 h)
  OP_GRAPH = 56,  // + option index
  OP_START = 64,  // + page
  OP_FUNC = 72,   // + Function (dropdown list entries; keep last)
};
static bool isDropOption(uint8_t op) { return op >= OP_FUNC; }
static const uint8_t SLEEP_OPTS[] = {0, 5, 10, 30, 60}, ROT_OPTS[] = {0, 15, 30, 60}, GRAPH_OPTS[] = {15, 30, 60};
static bool settingsChanged = false, restartArmed = false, restartNow = false;

bool uiTakeSettingsChanged() { bool c = settingsChanged; settingsChanged = false; return c; }
bool uiTakeRestart() { bool r = restartNow; restartNow = false; return r; }

static int toPct(uint8_t v) { return (v * 100 + 127) / 255; }
static uint8_t stepPct(uint8_t v, int dir) {  // backlight in 10% steps, never fully off
  int pct = (toPct(v) + 5) / 10 * 10 + dir * 10;
  return std::min(std::max(pct, 10), 100) * 255 / 100;
}

static void applyOp(uint8_t op) {
  if (op != OP_RESTART) restartArmed = false;
  Settings before = settings;
  switch (op) {
    case OP_BACK: detail = DET_NONE; dropOpen = false; return;
    case OP_BRIGHT_DN: settings.brightness = stepPct(settings.brightness, -1); break;
    case OP_BRIGHT_UP: settings.brightness = stepPct(settings.brightness, +1); break;
    case OP_NBRIGHT_DN: settings.nightBright = stepPct(settings.nightBright, -1); break;
    case OP_NBRIGHT_UP: settings.nightBright = stepPct(settings.nightBright, +1); break;
    case OP_NFROM_DN: settings.nightFrom = (settings.nightFrom + 23) % 24; break;
    case OP_NFROM_UP: settings.nightFrom = (settings.nightFrom + 1) % 24; break;
    case OP_NTO_DN: settings.nightTo = (settings.nightTo + 23) % 24; break;
    case OP_NTO_UP: settings.nightTo = (settings.nightTo + 1) % 24; break;
    case OP_NIGHT: settings.nightOn = !settings.nightOn; break;
    case OP_FUNC_OPEN: dropOpen = !dropOpen; return;
    case OP_RESTART:  // two taps, so a stray touch can't reboot the panel
      if (restartArmed) restartNow = true;
      restartArmed = true;
      return;
    default:
      if (op >= OP_FUNC) {  // takes effect at once: going back from settings lands in the new Function
        settings.function = op - OP_FUNC;
        dropOpen = false;
        openFunction();
      } else if (op >= OP_START) settings.startPage = op - OP_START;
      else if (op >= OP_GRAPH) {
        settings.graphMin = GRAPH_OPTS[op - OP_GRAPH];
        if (settings.graphMin != before.graphMin) clearHistory();
      } else if (op >= OP_CLOCK) settings.clock24 = op - OP_CLOCK;
      else if (op >= OP_ROT) settings.rotateSec = ROT_OPTS[op - OP_ROT];
      else if (op >= OP_SLEEP) settings.sleepMin = SLEEP_OPTS[op - OP_SLEEP];
  }
  settingsChanged |= memcmp(&before, &settings, sizeof settings) != 0;
}

static void fmtHour(char* buf, size_t n, int h) {
  if (settings.clock24) snprintf(buf, n, "%02d:00", h);
  else snprintf(buf, n, "%d %s", (h + 11) % 12 + 1, h < 12 ? "AM" : "PM");
}

// ---- controls (each registers its own tap targets) ----
// A rounded button: a label, or for "+" / "-" the add and remove icons (so both match in width and weight).
static void button(int x, int y, int w, int h, const char* label, uint32_t col, uint8_t op, uint32_t bg = 0) {
  spr.fillSmoothRoundRect(x, y, w, h, h / 2, bg ? bg : field());
  if ((label[0] == '+' || label[0] == '-') && !label[1])
    text(x + w / 2, y + h / 2, label[0] == '+' ? ICON_ADD : ICON_REMOVE, I_S, col, middle_center);
  else
    text(x + w / 2, y + h / 2, label, F_BODYB, col, middle_center);
  hit(x - 6, y - 5, w + 12, h + 10, ACT_SET, op);  // a little larger than drawn
}

// rx = right edge; returns the left edge. mid = width of the value between the buttons.
static int stepper(int rx, int cy, const char* value, uint8_t opDn, uint8_t opUp, bool dim, int mid = 96) {
  uint32_t c = dim ? C_MUTED : C_TEXT;
  button(rx - 44, cy - 20, 44, 40, "+", c, opUp);
  text(rx - 44 - mid / 2, cy, value, F_STAT, c, middle_center);
  button(rx - 44 - mid - 44, cy - 20, 44, 40, "-", c, opDn);
  return rx - 44 - mid - 44;
}

// track: the control's backing (0 = the usual field colour; the radar's floats on the map use the base colour).
static void segmented(int rx, int cy, const char* const* labels, int n, int sel, uint8_t opBase, int sw = 62,
                      Act act = ACT_SET, uint32_t track = 0, uint32_t accent = 0) {
  const int sh = 40, x0 = rx - n * sw - 6;
  spr.fillSmoothRoundRect(x0, cy - sh / 2, n * sw + 6, sh, sh / 2, track ? track : field());
  for (int i = 0; i < n; i++) {
    int x = x0 + 3 + i * sw;
    if (i == sel) spr.fillSmoothRoundRect(x, cy - sh / 2 + 3, sw, sh - 6, (sh - 6) / 2, mix(accent ? accent : C_CYAN, C_CARD, 0.32f));
    text(x + sw / 2, cy, labels[i], F_BODY, i == sel ? C_TEXT : C_MUTED, middle_center);
    hit(x, cy - sh / 2 - 5, sw, sh + 10, act, opBase + i);
  }
}

static void toggle(int rx, int cy, bool on, uint8_t op) {
  const int tw = 62, th = 34, x = rx - tw;
  spr.fillSmoothRoundRect(x, cy - th / 2, tw, th, th / 2, on ? mix(C_GREEN, C_CARD, 0.6f) : field());
  spr.fillSmoothCircle(on ? x + tw - th / 2 : x + th / 2, cy, th / 2 - 4, on ? C_TEXT : C_MUTED);
  text(x - 14, cy, on ? "On" : "Off", F_BODY, on ? C_TEXT : C_MUTED, middle_right);
  hit(x - 60, cy - th / 2 - 8, tw + 60, th + 16, ACT_SET, op);
}

static void fmtAge(char* buf, size_t n, uint32_t s) {
  if (s == UINT32_MAX) snprintf(buf, n, "never");
  else if (s < 120) snprintf(buf, n, "%u s ago", unsigned(s));
  else if (s < 7200) snprintf(buf, n, "%u min ago", unsigned(s / 60));
  else snprintf(buf, n, "%u h ago", unsigned(s / 3600));
}

