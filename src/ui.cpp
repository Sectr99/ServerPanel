// ---------- detail views: one full-screen graph per series, with stats over the graph window ----------
// A value split for display: "31" + "%", "3.4" + "GB", "61" + degrees C. Returns false for "--".
static bool fmtSplit(float v, const char* unit, char* num, size_t n, const char*& u) {
  u = unit;
  if (isnan(v)) { snprintf(num, n, "--"); return false; }
  if (!strcmp(unit, "MB")) {
    if (v >= 1024) { snprintf(num, n, "%.1f", v / 1024); u = "GB"; }
    else snprintf(num, n, "%.0f", v);
    return true;
  }
  bool tenth = v > 0 && v < 10 && !strcmp(unit, "%") && fabsf(v - roundf(v)) >= 0.05f;  // 0.4% and 2.5%, but 0% and 5%
  snprintf(num, n, tenth ? "%.1f" : "%.0f", v);
  return true;
}
static void fmtVal(char* buf, size_t n, float v, const char* unit) {
  char num[16];
  const char* u;
  if (!fmtSplit(v, unit, num, sizeof num, u)) snprintf(buf, n, "--");
  else snprintf(buf, n, "%s%s%s", num, !strcmp(u, "MB") || !strcmp(u, "GB") ? " " : "", u);
}

// hi <= lo: autoscale. none: shown for the current value when there's no reading (e.g. "asleep" for a disk).
struct Series { const Hist* h; uint32_t col; float lo, hi; const char* name; const char* unit; const char* none = "--"; };

// One series: its value, min/avg/max chips, and a chart with dashed gridlines, their values at the right and the
// time along the bottom. big: the single-series layout (112 px value); otherwise compact, for two stacked series.
static void detailSeries(const Series& s, int x, int y, int w, int h, bool big) {
  float mn = NAN, mx = NAN, sum = 0, now = NAN;
  int cnt = 0, first = -1;
  for (int i = 0; i < s.h->count; i++) {
    float v = s.h->at(i);
    if (isnan(v)) continue;
    if (first < 0) first = i;
    mn = isnan(mn) ? v : fminf(mn, v);
    mx = isnan(mx) ? v : fmaxf(mx, v);
    sum += v; cnt++; now = v;
  }
  char num[16], buf[48];
  const char* u;
  int cy;  // where the chart card starts
  if (big) {
    const bool has = fmtSplit(now, s.unit, num, sizeof num, u);
    const char* shown = has ? num : s.none;
    text(x + 8, y + 2, shown, has ? F_XL : F_HUGE, has ? s.col : C_DIM);
    int nx = x + 8 + spr.textWidth(shown) + 6;
    if (has) { text(nx, y + 22, u, F_BIG, C_MUTED); nx += spr.textWidth(u) + 14; }
    text(nx, y + 80, "now", F_BODY, C_MUTED);
    cy = y + 128;
  } else {
    card(x, y, w, h);
    text(x + 22, y + 22, s.name, F_SMALL, C_DIM);
    const bool has = fmtSplit(now, s.unit, num, sizeof num, u);
    text(x + 22, y + 40, has ? num : s.none, F_BIG, has ? s.col : C_DIM);
    if (has) text(x + 22 + spr.textWidth(num) + 6, y + 52, u, F_BODY, C_MUTED);
    cy = y;
  }
  // Chips, right-aligned: MIN, AVG, MAX.
  const struct { const char* cap; float v; } st[] = {{"MAX", mx}, {"AVG", cnt ? sum / cnt : NAN}, {"MIN", mn}};
  int rx = x + w - (big ? 0 : 22);
  for (auto& c : st) {
    fmtVal(buf, sizeof buf, c.v, s.unit);
    spr.setFont(F_TITLE);
    const int cw = std::max(100, int(spr.textWidth(buf)) + 36), ch = 64, ty = big ? y + 18 : y + 16;
    spr.fillSmoothRoundRect(rx - cw, ty, cw, ch, 16, big ? C_CARD : field());
    text(rx - 18, ty + 10, c.cap, F_SMALL, C_DIM, top_right);
    text(rx - 18, ty + ch - 8, buf, F_TITLE, C_TEXT, bottom_right);
    rx -= cw + 12;
  }
  // The chart.
  int gx, gy, gw, gh;
  if (big) {
    card(x, cy, w, y + h - cy);
    gx = x + 22; gy = cy + 22; gw = w - 44 - 56; gh = y + h - cy - 22 - 46;
  } else {
    gx = x + 22; gy = y + 92; gw = w - 44 - 56; gh = h - 92 - 40;
  }
  float hi = s.hi > s.lo ? s.hi : fmaxf(isnan(mx) ? 1 : mx * 1.15f, s.lo + 1);
  float vlo = s.lo, vhi = hi;
  if (s.hi > s.lo) { auto r = fitRange(*s.h, s.lo, hi); vlo = r.first; vhi = r.second; }
  for (int k = 1; k <= 3; k++) {
    const int ly = gy + gh - gh * k / 4;
    for (int dx = gx; dx < gx + gw; dx += 8) spr.drawFastHLine(dx, ly, 3, C_TRACK);
    fmtVal(buf, sizeof buf, vlo + (vhi - vlo) * k / 4, s.unit);
    text(gx + gw + 56, ly, buf, F_SMALL, C_DIM, middle_right);
  }
  chart(gx, gy, gw, gh, *s.h, s.col, vlo, vhi, false);
  // Explain an empty graph, or the empty stretch before this series' history starts.
  int emptyW = first < 0 ? gw : XScale(gx, gw, s.h->count).xa(first) - gx;
  if (first < 0) snprintf(buf, sizeof buf, "No readings in the last %d min", settings.graphMin);
  else snprintf(buf, sizeof buf, "No data yet");
  spr.setFont(F_BODY);
  if (emptyW > spr.textWidth(buf) + 40) text(gx + emptyW / 2, gy + gh / 2, buf, F_BODY, C_DIM, middle_center);
  snprintf(buf, sizeof buf, "%d min ago", settings.graphMin);
  text(gx, gy + gh + 12, buf, F_SMALL, C_DIM);
  text(gx + gw, gy + gh + 12, "now", F_SMALL, C_DIM, top_right);
}

