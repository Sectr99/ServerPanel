// RadarOp: 0..N_RADAR_ZOOMS-1 pick a zoom; R_DIGIT + 0..9 types a digit.
enum RadarOp : uint8_t { R_SHEET = 8, R_BACK, R_DEL, R_SAVE, R_ALERT, R_ALERT_NEXT, R_DIGIT = 16 };
static void radarOp(uint8_t op) {
  if (op < N_RADAR_ZOOMS) {
    if (settings.radarZoom != op) { settings.radarZoom = op; settingsChanged = true; radarHave = false; }
    return;
  }
  size_t n = strlen(radarEntry);
  switch (op) {
    case R_SHEET: radarSheet = true; radarEntry[0] = 0; radarLookup = RL_IDLE; return;
    case R_BACK: radarSheet = false; radarAlert = -1; return;
    case R_ALERT: radarAlert = wx && wx->nAlerts ? 0 : -1; return;
    case R_ALERT_NEXT: if (wx && wx->nAlerts) radarAlert = (radarAlert + 1) % wx->nAlerts; return;
    case R_DEL: if (n) radarEntry[n - 1] = 0; radarLookup = RL_IDLE; return;
    case R_SAVE:
      if (n == 5 && radarLookup != RL_LOOKING) {
        memcpy(radarAsk, radarEntry, sizeof radarAsk);
        radarAsked = true;
        radarLookup = RL_LOOKING;
      }
      return;
    default:
      if (op >= R_DIGIT && op < R_DIGIT + 10 && n < 5) { radarEntry[n] = char('0' + op - R_DIGIT); radarEntry[n + 1] = 0; }
      radarLookup = RL_IDLE;
  }
}

