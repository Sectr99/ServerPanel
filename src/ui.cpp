static void spotifyOp(uint8_t cmd, float at) {
  if (cmd == SPU_VOLUME_OPEN || cmd == SPU_VOLUME_CLOSE) { spVolume = cmd == SPU_VOLUME_OPEN; return; }
  if (cmd == SPU_LIBRARY || cmd == SPU_DEVICES) { spSheet = cmd; return; }
  if (cmd == SPU_SHEET_CLOSE) { spSheet = 0; return; }
  int arg = 0;
  if (cmd >= SPU_DEVICE) { arg = cmd - SPU_DEVICE; cmd = SP_DEVICE; spSheet = 0; }
  else if (cmd >= SPU_ITEM) { arg = cmd - SPU_ITEM; cmd = SP_CONTEXT; spSheet = 0; }
  switch (cmd) {
    case SP_PLAY: case SP_PAUSE: cmd = sp.playing ? SP_PAUSE : SP_PLAY; break;
    case SP_SEEK: arg = int(at * sp.durationMs); break;
    case SP_VOLUME: arg = int(at * 100 + 0.5f); break;
    case SP_SHUFFLE: arg = !sp.shuffle; break;
    case SP_REPEAT: arg = (sp.repeat + 1) % 3; break;
    case SP_LIKE: arg = !sp.liked; break;
  }
  spCmd = spFlash = cmd;
  spArg = arg;
}

